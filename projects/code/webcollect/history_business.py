def _page_context(value):
    # Countdown parameters change the title but do not create a new business.
    return ('网页「<countdown-running>」'
            if re.fullmatch(r'网页「\(\d{2}:\d{2}:\d{2}\) 倒计时中\.\.\.」', value)
            else value)


def _tree_target(root, step):
    """Read the actual bound frame tree; never accept annotation claims alone."""
    relative = Path(step.get('ui_tree_path', ''))
    if relative.is_absolute() or '..' in relative.parts or not relative.parts:
        raise ValueError('Unsafe or missing original UI tree path')
    path = root / relative
    if path.is_symlink() or not path.resolve().is_relative_to(root):
        raise ValueError('UI tree escapes the original sample')
    tree = json.loads(path.read_text(encoding='utf-8'))
    elements = tree['elements']
    action = step['action']; target = action['target_element_id']
    found = [(i, e) for i, e in enumerate(elements) if e.get('element_id') == target]
    if len(found) != 1:
        raise ValueError('Missing or ambiguous actual target')
    index, element = found[0]
    if (element.get('element_type') != action.get('target_control_type')
            or element.get('text') != action.get('target_text')
            or element.get('bbox') != action.get('target_bbox')
            or element.get('visible') is not True or element.get('enabled') is not True):
        raise ValueError('Annotation target is not corroborated by original UI tree')
    if action['action_type'] == 'type' and element.get('inputable') is not True:
        raise ValueError('Typed control is not editable')
    return elements, index


def _recent_frame_context(root, annotation, rule):
    """Corroborate recent rules without changing legacy matching semantics."""
    context = rule['frame_context']
    if annotation.get('app_info', {}).get('app_name') != context['app_name']:
        raise ValueError('Historical application context differs')
    identities, files = {}, []
    for step in annotation['steps']:
        relative = Path(step.get('ui_tree_path', ''))
        if relative.is_absolute() or '..' in relative.parts or not relative.parts:
            raise ValueError('Unsafe or missing original frame tree')
        path = root / relative
        if path.is_symlink() or not path.resolve().is_relative_to(root):
            raise ValueError('Frame tree escapes original sample')
        tree = json.loads(path.read_text(encoding='utf-8'))
        if (tree.get('image_path') != step.get('image_path') or
                tree.get('screen_resolution') != annotation['device_info']['screen_resolution']):
            raise ValueError('Original frame image/geometry binding differs')
        elements = tree['elements']
        by_id = {e['element_id']: e for e in elements}
        if len(by_id) != len(elements):
            raise ValueError('Ambiguous original tree identity')
        def signature(e):
            return e.get('element_type'), e.get('native_role'), e.get('text')
        def parents(e):
            result, seen = [], set()
            while e.get('parent_id') != 'root':
                parent = e.get('parent_id')
                if parent in seen or parent not in by_id:
                    raise ValueError('Invalid target ancestor topology')
                seen.add(parent); e = by_id[parent]
                if e.get('visible') is not True or e.get('enabled') is not True:
                    raise ValueError('Historical target ancestor is unavailable')
                result.append(signature(e))
            return result
        headings = [e for e in elements if signature(e) == context['heading']
                    and e.get('visible') is True and e.get('enabled') is True]
        if len(headings) != 1:
            raise ValueError('Missing or ambiguous original business heading')
        action, call = step['action'], step['tool_call']
        if call.get('context') != 'Web / ' + context['app_name']:
            raise ValueError('Tool context differs from observed business')
        kind, target = action['action_type'], action.get('target_element_id')
        if kind == 'hotkey' and (call.get('arguments') != {'keys': ['ctrl', 'a']}
                                 or action.get('input_text') != 'ctrl+a'):
            raise ValueError('Replacement hotkey does not match executed keys')
        if kind == 'complete' and call.get('arguments') != {'status': 'success'}:
            raise ValueError('Completion tool did not report success')
        if target:
            elements, position = _tree_target(root, step); element = elements[position]
            identity = identities.setdefault(target, len(identities))
            role, expected_parents = context['targets'][identity]
            if element.get('native_role') != role or parents(element) != expected_parents:
                raise ValueError('Original control role/ancestor topology differs')
            peers = [e for e in elements if signature(e) == signature(element)
                     and e.get('visible') is True and e.get('enabled') is True
                     and parents(e) == expected_parents]
            if len(peers) != 1:
                raise ValueError('Ambiguous original business control')
            if kind == 'click':
                point = action.get('coordinate'); args = call.get('arguments', {})
                if (element.get('clickable') is not True or not isinstance(point, list) or len(point) != 2
                        or point != [args.get('x'), args.get('y')]
                        or not element['bbox'][0] <= point[0] < element['bbox'][2]
                        or not element['bbox'][1] <= point[1] < element['bbox'][3]):
                    raise ValueError('Executed click does not hit original target')
        files.append(step['ui_tree_path'])
    return files


def classification_evidence(annotation, sample_root=None):
    """Return an exact evidence-backed business match, or None for UNKNOWN.

    sample_root is mandatory: the caller owns package SHA validation, while this
    function verifies action-to-tree binding. No source tree is modified. The
    returned identity is independent of origin, sample ID and input parameters.
    """
    if sample_root is None or not isinstance(annotation, dict):
        return None
    try:
        root = Path(sample_root).resolve(strict=True)
        steps = annotation['steps']
        if (annotation.get('completion_status') != 'success' or not steps
                or [s.get('step_id') for s in steps] != list(range(1, len(steps) + 1))
                or steps[-1].get('action', {}).get('action_type') != 'complete'):
            return None
        identities, pattern, pages = {}, [], []
        for index, step in enumerate(steps):
            action, call, result = step['action'], step['tool_call'], step['tool_result']
            kind = action['action_type']; target = action.get('target_element_id', '')
            if (call.get('tool_name') != kind or result.get('status') != 'success'
                    or result.get('error') not in ('', None) or step.get('exception_evidence')
                    or kind == 'complete' and index != len(steps) - 1):
                return None
            if kind == 'type' and (not str(action.get('input_text', '')).strip()
                                  or call.get('arguments', {}).get('text') != action['input_text']):
                return None
            identity = identities.setdefault(target, len(identities)) if target else -1
            pattern.append((kind, action.get('target_control_type') or '', action.get('target_text', ''), identity))
            pages.append(_page_context(step['page_name']))
        matches = [rule for rule in RULES if rule['pages'] == pages and rule['pattern'] == pattern]
        if len(matches) != 1:
            return None
        rule = matches[0]; anonymous = {i: (ordinal, neighbors) for i, ordinal, neighbors in rule['anonymous_contexts']}
        tree_files = _recent_frame_context(root, annotation, rule) if 'frame_context' in rule else []
        for index, step in enumerate(steps):
            action = step['action']
            if not action.get('target_element_id'):
                continue
            elements, position = _tree_target(root, step)
            if step['ui_tree_path'] not in tree_files:
                tree_files.append(step['ui_tree_path'])
            if index not in anonymous:
                continue
            expected_ordinal, expected_neighbors = anonymous[index]
            editable = [e['element_id'] for e in elements if e.get('inputable')]
            if editable.index(action['target_element_id']) != expected_ordinal:
                return None
            neighbors = [(e['element_type'], e['native_role'], e['text'])
                         for e in elements[max(0, position - 1):position + 2]]
            if expected_neighbors[0][2] == '<character-count>':
                if not re.fullmatch(r'\d+ 字符', neighbors[0][2]):
                    return None
                neighbors[0] = (*neighbors[0][:2], '<character-count>')
            if neighbors != expected_neighbors:
                return None
        return {'strategy_id': rule['strategy_id'], 'classifier_version': VERSION,
                'matched_rule_source_sample': rule['source_sample'],
                'matched_rule_annotation_sha256': rule['source_annotation_sha256'],
                'verified_target_tree_files': tree_files,
                'scope': 'business identity only; not a quality or human review decision'}
    except (OSError, ValueError, KeyError, TypeError, IndexError):
        return None


def annotation_business_strategy(annotation, sample_root=None):
    evidence = classification_evidence(annotation, sample_root)
    return evidence['strategy_id'] if evidence else None
